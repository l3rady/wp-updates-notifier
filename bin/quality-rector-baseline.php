<?php
/**
 * Writes the baseline of the Rector quality gate (docker/quality/rector-baseline.php).
 *
 * Usage: php bin/quality-rector-baseline.php <rector output in JSON> <baseline file to write>
 *
 * The input is `rector process --config=rector-quality.php --dry-run --output-format=json`, without the baseline
 * applied.
 * The output is a skip list: each rule that would change a file, with the files. rector-quality.php merges it into
 * withSkip() when WPUN_QUALITY_BASELINE is set. Run through `make quality-baseline`, not by hand.
 */

if ( 3 !== $argc ) {
	fwrite( STDERR, "Usage: php bin/quality-rector-baseline.php <rector.json> <baseline.php>\n" );
	exit( 2 );
}

$report = json_decode( (string) file_get_contents( $argv[1] ), true );
if ( ! is_array( $report ) || ! isset( $report['file_diffs'] ) || ! is_array( $report['file_diffs'] ) ) {
	fwrite( STDERR, "Not a Rector JSON report: {$argv[1]}\n" );
	exit( 1 );
}

$skips = array();
foreach ( $report['file_diffs'] as $diff ) {
	foreach ( $diff['applied_rectors'] as $rule ) {
		$skips[ $rule ][] = $diff['file'];
	}
}
ksort( $skips );

$out  = "<?php\n";
$out .= "/**\n";
$out .= " * Baseline of the Rector quality gate: the rules that still have something to say about a file.\n";
$out .= " *\n";
$out .= " * Generated by `make quality-baseline` (bin/quality-rector-baseline.php); do not edit by hand. Keep it\n";
$out .= " * shrinking: when a file is fixed, regenerate. Rector does not report a skip that is no longer needed, so only\n";
$out .= " * regenerating removes it. It skips a rule for a whole file, so a new finding of the same rule in a listed file\n";
$out .= " * goes unnoticed.\n";
$out .= " *\n";
$out .= " * @package wp-updates-notifier\n";
$out .= " */\n\n";
$out .= "return array(\n";
foreach ( $skips as $rule => $files ) {
	$files = array_unique( $files );
	sort( $files );
	$out .= "\t\\" . $rule . "::class => array(\n";
	foreach ( $files as $file ) {
		$out .= "\t\tdirname( __DIR__, 2 ) . '/" . $file . "',\n";
	}
	$out .= "\t),\n";
}
$out .= ");\n";

file_put_contents( $argv[2], $out );
